import type { Market } from '../types';
import {isComboMarket} from './comboPolicy';

/**
 * Contract identity and grouping always use the original provider text.
 * Translation is applied only when rendering; IDs, lines, prices and saved
 * selection data remain unchanged.
 */
export type MarketCategory = 'main' | 'goals' | 'mixed' | 'corners' | 'cards' | 'htft' | 'players' | 'other';
export type MarketLanguage = 'al' | 'en';

const normalized = (value: unknown): string =>
  String(value ?? '').trim().replace(/\s+/g, ' ').toLowerCase();

/** All handicap variants are excluded from the current sportsbook offer.
 * "Asian Total" is not necessarily a handicap, so do not discard it simply
 * because its name includes "Asian".
 */
export function isHandicapMarket(_market: Pick<Market, 'name' | 'marketType'>): boolean {
  return false; // no name-based market exclusion; admin/provider state owns availability
}

/** Hide unnamed/generated placeholders, not real short provider names.
 * "Total", "Result", "Corners", "Cards", etc. ARE original provider names.
 */
export function isIdentifiedMarket(market: Market): boolean {
  const name = String(market.name ?? '').trim();
  if (!name) return false;
  return !/^(?:market|unknown|unverified market(?:\b.*)?|cols-?\d+|total-2|fora-2|match market)$/i.test(name);
}

export function marketBaseName(market: Market): string {
  const raw = String(market.name ?? '').trim();
  const explicit = String(market.line ?? '').trim().replace(',', '.');
  const suffix = raw.match(/\s+(-?\d+(?:[.,]\d+)?)$/);
  if (!suffix) return raw;
  const embedded = suffix[1].replace(',', '.');
  if (explicit && explicit === embedded) return raw.slice(0, suffix.index ?? raw.length).trim();
  if (!explicit && /[.,]\d+$/.test(suffix[1]) &&
      /\b(?:total|over\s*\/?\s*under|goals?|corners?|cards?|handicap)\b/i.test(raw)) {
    return raw.slice(0, suffix.index ?? raw.length).trim();
  }
  return raw;
}

export function marketLineValue(market: Market): string {
  const given = String(market.line ?? '').trim();
  if (given && !/^#\d+$/.test(given)) return given;
  const raw = String(market.name ?? '').trim();
  if (marketBaseName(market) !== raw) {
    return raw.match(/\s+(-?\d+(?:[.,]\d+)?)$/)?.[1] ?? '';
  }
  return '';
}


/**
 * Only synthetic Bet Builders (not upstream/provider markets) may share a UI
 * group without sharing a provider family/line. The outcome label generated by
 * our backend includes the original leg contract IDs, regardless of the
 * arbitrary template name chosen by the administrator.
 *
 * Example: "DC X2 + TOTAL Under 2.5" => "Double Chance + Total Goals".
 * Other/outdated/unknown templates remain separate rather than being guessed.
 * Every builder retains its own market/outcome ID and individual price.
 */
export function betBuilderGroup(market: Market): { key: string; title: string } | null {
  if (!/^bet builder\s*:/i.test(String(market.name ?? '').trim())) return null;
  const outcomes = market.outcomes ?? [];
  if (outcomes.length !== 1) return null;
  const raw = String(outcomes[0]?.name ?? '');
  const legs = raw.split(/\s+\+\s+/);
  if (legs.length < 2 || legs.length > 5) return null;

  const order = ['1X2', 'DC', 'BTTS', 'TOTAL'] as const;
  const names: Record<string, string> = {
    '1X2': '1X2', DC: 'Double Chance', BTTS: 'Both Teams to Score', TOTAL: 'Total Goals',
  };
  const types = legs.map(part => part.match(/^(1X2|DC|BTTS|TOTAL)\s+\S/i)?.[1]?.toUpperCase());
  if (types.some(type => !type || !names[type])) return null;
  const sorted = (types as string[]).sort((a, b) => order.indexOf(a as typeof order[number]) - order.indexOf(b as typeof order[number]));
  return {
    key: 'synthetic-bet-builder::' + sorted.join('+'),
    title: 'Bet Builder: ' + sorted.map(type => names[type]).join(' + '),
  };
}

/** Never join unrelated provider line-less markets; merge only real numeric lines
 * in the same provider family and period. Synthetic Bet Builders are the
 * exception: they group visually by their verified contract signature.
 */
export function marketGroupKey(market: Market): string {
  const syntheticGroup = betBuilderGroup(market);
  if (syntheticGroup) return syntheticGroup.key;
  const identity = String(market.extId ?? '').trim() || normalized(marketBaseName(market));
  const native=identity.match(/^(yb\d+)@([\w-]*)$/);
  if(native){
    try{
      const spec=atob(native[2].replace(/-/g,'+').replace(/_/g,'/'));
      const fixed=spec.split('|').filter(p=>!p.startsWith('bc_id=')&&!p.startsWith('hcp=')).sort().join('|');
      return [normalized(market.marketType),market.period??0,native[1],fixed,normalized(marketBaseName(market))].join('::');
    }catch{/* An unfamiliar identity keeps its original isolated group. */}
  }
  const family = [normalized(market.marketType), market.period ?? 0, identity, normalized(marketBaseName(market))].join('::');
  return marketLineValue(market) ? family : family + '::' + String(market.id);
}

/** Subjects come before bet types: "Corners. Result" belongs to Corners,
 * not Main/Result. Period labels are a secondary distinction.
 */
export function marketCategoryOf(market: Market): MarketCategory {
  const name = normalized(market.name);
  const type = normalized(market.marketType);
  if (isComboMarket(market)) return 'mixed';
  if (type === 'corners' || /\bcorners?\b|\bcorner kicks?\b/.test(name)) return 'corners';
  if (type === 'cards' || /\bcards?\b|\bbookings?\b|yellow card|red card|disciplin/.test(name)) return 'cards';
  if (/\bplayers?\b|goalscorer|scorer|to be booked|player shots?/.test(name)) return 'players';
  if (/\b(?:result|winner|1x2)\b.*\b(?:total|goals|btts|both teams)\b|\b(?:total|goals|btts)\b.*\b(?:both teams|btts)\b/.test(name)) return 'mixed';
  if (/halftime\s*\/?\s*fulltime|half\s*time\s*\/\s*full\s*time|ht\s*\/\s*ft|\b(?:1st|2nd|first|second)\s+half\b|\bperiod\b/.test(name) ||
      Number(market.period ?? 0) === 1 || Number(market.period ?? 0) === 2) return 'htft';
  if (/\b(?:1x2|match result|full time result|winner|double chance|draw no bet|moneyline|qualify|result)\b/.test(name) || type === '1x2') return 'main';
  if (type === 'over_under' || /\bgoals?\b|\btotal\b|over\s*\/?\s*under|both teams|btts|correct score|odd\s*\/\s*even/.test(name)) return 'goals';
  return 'other';
}

/** Display the exact provider wording; localisation is a separate future task. */
export function marketDisplayTitle(market: Market, _lang: MarketLanguage, withLine = false): string {
  const raw=String(market.name??'');
  if(!withLine)return raw;
  const line=String(market.line??'').trim();
  return line&& !raw.includes(line)?raw+' ('+line+')':raw;
}

/** Never rewrite selection names, especially native player identities. */
export function marketSelectionLabel(raw: string, _lang: MarketLanguage, _marketName?: string,
  _matchName?: string, _outcomeCode?: string, _marketLine?: string): string {
  return String(raw??'');
}

